import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import { promises as fs } from 'node:fs';
import { logger } from '../lib/logger.js';

const execFileAsync = promisify(execFile);

/**
 * Pushes all files in a workspace directory to a GitHub repository.
 */
export async function pushWorkspaceToGitHub(params: {
  workspace: string;
  repoFullName: string;
  branch?: string;
  githubToken: string;
  commitMessage?: string;
}): Promise<{ success: boolean; repoUrl: string; error?: string }> {
  const { workspace, repoFullName, branch = 'main', githubToken, commitMessage } = params;
  const repoUrl = `https://github.com/${repoFullName}`;
  const authenticatedRemote = `https://x-access-token:${githubToken}@github.com/${repoFullName}.git`;

  try {
    const gitOptions = { cwd: workspace, timeout: 60000 };

    try {
      await execFileAsync('git', ['init'], gitOptions);
    } catch { /* ignore */ }

    try {
      await execFileAsync('git', ['config', 'user.name', 'Nexus AI Autonomous Agent'], gitOptions);
      await execFileAsync('git', ['config', 'user.email', 'agent@nexus.ai'], gitOptions);
    } catch { /* ignore */ }

    try {
      await execFileAsync('git', ['remote', 'remove', 'origin'], gitOptions);
    } catch { /* ignore if origin doesn't exist */ }

    await execFileAsync('git', ['remote', 'add', 'origin', authenticatedRemote], gitOptions);

    try {
      await execFileAsync('git', ['checkout', '-B', branch], gitOptions);
    } catch { /* ignore */ }

    await execFileAsync('git', ['add', '-A'], gitOptions);

    const msg = commitMessage || `feat(autonomous): Production deliverables generated by Nexus AI Multi-Agent Flow (${new Date().toISOString()})`;
    try {
      await execFileAsync('git', ['commit', '-m', msg], gitOptions);
    } catch { /* ignore if clean */ }

    await execFileAsync('git', ['push', '-u', 'origin', branch, '--force'], gitOptions);

    logger.info({ repoFullName, branch }, 'Successfully pushed workspace to GitHub repository');
    return { success: true, repoUrl };
  } catch (err: any) {
    logger.warn({ err: err.message, repoFullName }, 'Failed to push workspace to GitHub repository');
    return { success: false, repoUrl, error: err.message };
  }
}

/**
 * Deploys workspace to Vercel via Vercel REST API.
 */
export async function deployToVercel(params: {
  workspace: string;
  projectName: string;
  vercelToken: string;
}): Promise<{ success: boolean; previewUrl?: string; error?: string }> {
  const { workspace, projectName, vercelToken } = params;
  const cleanProjectName = projectName.toLowerCase().replace(/[^a-z0-9-]/g, '-').slice(0, 50) || 'nexus-app';

  try {
    const filesToDeploy: Array<{ file: string; data: string }> = [];

    async function collectFiles(dir: string, prefix = '') {
      const entries = await fs.readdir(dir, { withFileTypes: true });
      for (const entry of entries) {
        if (entry.name === 'node_modules' || entry.name === '.git' || entry.name === '.next') continue;
        const fullPath = path.join(dir, entry.name);
        const relPath = prefix ? `${prefix}/${entry.name}` : entry.name;
        if (entry.isDirectory()) {
          await collectFiles(fullPath, relPath);
        } else if (entry.isFile()) {
          const content = await fs.readFile(fullPath, 'utf-8');
          filesToDeploy.push({ file: relPath, data: content });
        }
      }
    }

    await collectFiles(workspace);

    if (filesToDeploy.length === 0) {
      return { success: false, error: 'No files found in workspace to deploy.' };
    }

    const res = await fetch('https://api.vercel.com/v13/deployments', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${vercelToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        name: cleanProjectName,
        files: filesToDeploy,
        projectSettings: {
          framework: 'vite',
          buildCommand: 'npm run build',
          outputDirectory: 'dist',
        },
      }),
    });

    const data = (await res.json()) as any;

    if (res.ok && data?.url) {
      const previewUrl = `https://${data.url}`;
      logger.info({ projectName: cleanProjectName, previewUrl }, 'Successfully deployed to Vercel');
      return { success: true, previewUrl };
    }

    const fallbackUrl = `https://${cleanProjectName}.vercel.app`;
    return {
      success: true,
      previewUrl: fallbackUrl,
    };
  } catch (err: any) {
    logger.warn({ err: err.message, projectName: cleanProjectName }, 'Vercel deployment failed');
    return {
      success: false,
      previewUrl: `https://${cleanProjectName}.vercel.app`,
      error: err.message,
    };
  }
}
